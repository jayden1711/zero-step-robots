"""Cartpole LQR baseline: linearise the MuJoCo model about the upright rest state by finite differences, solve the
discrete Riccati equation (Q = I, R = 1, no tuning), write a Python controller. One controller per physics variant
(a model-based reference that knows the physics) plus the stock one, which is also scored on every variant.

usage: python scripts/make_lqr.py OUT_DIR     (from the repo root; run through sim-run)
"""
import sys
from pathlib import Path

import mujoco
import numpy as np

from zsr.tasks import make_env
from zsr.variants import variant_names


def linearise(variant):
    env = make_env("cartpole", variant)
    m, d, fs = env.unwrapped.model, env.unwrapped.data, env.unwrapped.frame_skip

    def f(x, u):
        mujoco.mj_resetData(m, d)
        d.qpos[:], d.qvel[:], d.ctrl[:] = x[:2], x[2:], u
        for _ in range(fs):
            mujoco.mj_step(m, d)
        return np.concatenate([d.qpos, d.qvel])

    x0, u0, eps = np.zeros(4), np.zeros(1), 1e-6
    A = np.stack([(f(x0 + eps * e, u0) - f(x0 - eps * e, u0)) / (2 * eps) for e in np.eye(4)], 1)
    B = ((f(x0, u0 + eps) - f(x0, u0 - eps)) / (2 * eps)).reshape(4, 1)
    env.close()
    return A, B


def dlqr(A, B, Q, R, iters=200000):
    P = Q.copy()
    for _ in range(iters):
        K = np.linalg.solve(R + B.T @ P @ B, B.T @ P @ A)
        Pn = Q + A.T @ P @ (A - B @ K)
        if np.abs(Pn - P).max() < 1e-12:
            P = Pn
            break
        P = Pn
    return np.linalg.solve(R + B.T @ P @ B, B.T @ P @ A)


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    for v in [None] + variant_names("cartpole"):
        A, B = linearise(v)
        K = dlqr(A, B, np.eye(4), np.eye(1))[0]
        name = v or "stock"
        (out / f"cartpole_lqr_{name}.py").write_text(
            f'"""LQR (Q=I, R=1) for cartpole physics variant: {name}. Generated by scripts/make_lqr.py."""\n'
            f"K = {tuple(float(k) for k in -K)!r}\n\n\ndef act(obs):\n    return [sum(k * o for k, o in zip(K, obs))]\n")
        print(name, "K =", -K, "open-loop eig max |λ| =", np.abs(np.linalg.eigvals(A)).max())


if __name__ == "__main__":
    main()
